// Build the tree data structure with childIds computed
function buildTreeData(rawNodes: TaxonNode[]): TreeData {
  const nodeMap: Record<string, TaxonNode> = {};

  // First pass: populate nodeMap and initialize childIds
  for (const node of rawNodes) {
    nodeMap[node.id] = { ...node, childIds: [] };
  }

  // Second pass: assign children
  for (const node of rawNodes) {
    if (node.parentId && nodeMap[node.parentId]) {
      nodeMap[node.parentId].childIds!.push(node.id);
    }
  }

  return {
    nodes: nodeMap,
    rootId: "luca",
  };
}

